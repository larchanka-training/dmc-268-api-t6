#!/usr/bin/env bash

# Renders alertmanager/alertmanager.yml of the monitoring stack (docs/MONITORING.md §Alerts).
# Sourced by deploy.sh; CI renders both variants and checks them with amtool (job monitoring-validate).
# Alertmanager expands no environment variables, so the chat id is written into the file and the
# bot token into a separate file read through bot_token_file: it never appears in the config.

TELEGRAM_TOKEN_FILE_IN_CONTAINER="/etc/alertmanager/secrets/telegram_bot_token"

# The routing shared by both variants: one message per alert name and environment, a reminder
# every 4 hours while it fires, and a message when it resolves.
render_alertmanager_route() {
  local receiver="$1"
  cat <<YAML
route:
  receiver: ${receiver}
  group_by: [alertname, environment]
  group_wait: 30s
  group_interval: 5m
  repeat_interval: 4h
YAML
}

# render_alertmanager_config <file> <telegram chat id or empty>
# With a chat id: the receiver telegram, the token read from TELEGRAM_TOKEN_FILE_IN_CONTAINER.
# Without one: the receiver none, which delivers nothing; alerts stay visible in Alertmanager.
render_alertmanager_config() {
  local file="$1" chat_id="$2"
  if [[ -n "${chat_id}" && ! "${chat_id}" =~ ^-?[0-9]{1,20}$ ]]; then
    echo "ALERT_TELEGRAM_CHAT_ID must be a numeric Telegram chat id" >&2
    return 1
  fi
  {
    echo "# Generated by deploy/monitoring/deploy.sh; do not edit on the host."
    echo "templates:"
    echo "  - /etc/alertmanager/templates/*.tmpl"
    echo
    if [[ -n "${chat_id}" ]]; then
      render_alertmanager_route telegram
      cat <<YAML

receivers:
  - name: telegram
    telegram_configs:
      - bot_token_file: ${TELEGRAM_TOKEN_FILE_IN_CONTAINER}
        chat_id: ${chat_id}
        parse_mode: HTML
        send_resolved: true
        message: '{{ template "dmc.telegram.message" . }}'
YAML
    else
      render_alertmanager_route none
      cat <<YAML

receivers:
  - name: none
YAML
    fi
  } > "${file}"
}
