#!/usr/bin/env bash

# Renders alertmanager/alertmanager.yml of the monitoring stack (docs/MONITORING.md §5).
# Sourced by deploy.sh; CI renders both variants and checks them with amtool (job monitoring-validate).
# Alertmanager expands no environment variables, so the chat id is written into the file and the
# bot token into a separate file read through bot_token_file: it never appears in the config.

TELEGRAM_TOKEN_FILE_IN_CONTAINER="/etc/alertmanager/secrets/telegram_bot_token"

# The routing shared by both variants. A state alert: one message per alert name and environment,
# a reminder every 4 hours while it fires, a message when it resolves. An event alert (label
# kind="event", rules/alerts.yml): sent once and never as RESOLVED, because it resolves only by
# leaving its time window; events of 90 seconds share one message, so the failed run and the dead
# letter of one exhausted Run (docs/PIPELINE_SPEC.md §4.4) arrive together.
render_alertmanager_route() {
  local receiver="$1" events_receiver="$2"
  cat <<YAML
route:
  receiver: ${receiver}
  group_by: [alertname, environment]
  group_wait: 30s
  group_interval: 5m
  repeat_interval: 4h
  routes:
    - matchers: [kind="event"]
      receiver: ${events_receiver}
      group_by: [environment]
      group_wait: 90s
YAML
}

# render_alertmanager_config <file> <telegram chat id or empty>
# With a chat id: the receiver telegram, the token read from TELEGRAM_TOKEN_FILE_IN_CONTAINER.
# Without one: the receiver none, which delivers nothing; alerts stay visible in Alertmanager.
render_alertmanager_config() {
  local file="$1" chat_id="$2"
  if [[ -n "${chat_id}" && ! "${chat_id}" =~ ^-?[0-9]{1,20}$ ]]; then
    echo "ALERT_TELEGRAM_CHAT_ID must be a numeric Telegram chat id" >&2
    return 1
  fi
  {
    echo "# Generated by deploy/monitoring/deploy.sh; do not edit on the host."
    echo "templates:"
    echo "  - /etc/alertmanager/templates/*.tmpl"
    echo
    if [[ -n "${chat_id}" ]]; then
      render_alertmanager_route telegram telegram-events
      local resolved
      for resolved in true false; do
        if [[ "${resolved}" == true ]]; then echo; echo "receivers:"; fi
        cat <<YAML
  - name: $([[ "${resolved}" == true ]] && echo telegram || echo telegram-events)
    telegram_configs:
      - bot_token_file: ${TELEGRAM_TOKEN_FILE_IN_CONTAINER}
        chat_id: ${chat_id}
        parse_mode: HTML
        send_resolved: ${resolved}
        message: '{{ template "dmc.telegram.message" . }}'
YAML
      done
    else
      render_alertmanager_route none none
      cat <<YAML

receivers:
  - name: none
YAML
    fi
  } > "${file}"
}
